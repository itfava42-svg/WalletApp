private enum class ReminderFilter(
    val title: String
) {
    ALL("همه"),
    TODAY("امروز"),
    NEXT_THREE_DAYS("۳ روز آینده"),
    THIS_WEEK("این هفته"),
    OVERDUE("عقب‌افتاده"),
    COMPLETED("انجام‌شده")
}

@OptIn(ExperimentalMaterial3Api::class)
@androidx.compose.runtime.Composable
fun ReminderScreen(
    onBack: () -> Unit,
    onAddReminder: () -> Unit,
    onEditReminder: (Reminder) -> Unit
) {

    val context =
        androidx.compose.ui.platform.LocalContext.current

    LaunchedEffect(Unit) {
        ReminderStore.attachContext(context)
    }

    var refreshKey by remember {
        mutableStateOf(0)
    }

    var selectedFilter by remember {
        mutableStateOf(
            ReminderFilter.OVERDUE
        )
    }

    val reminders =
        remember(
            refreshKey,
            ReminderStore.reminders.size
        ) {
            ReminderStore.reminders.toList()
        }

    val now =
        System.currentTimeMillis()

    val todayStart =
        startOfDay(now)

    val tomorrowStart =
        todayStart +
            DAY_MILLIS

    val threeDaysEnd =
        todayStart +
            (4L * DAY_MILLIS)

    val weekEnd =
        endOfWeek(now)

    val activeReminders =
        reminders.filter {
            it.isActive &&
                !it.isCompleted
        }

    val overdueLoanReminders =
        activeReminders
            .filter {
                it.isAutoGenerated &&
                    isOverdue(it, now)
            }
            .sortedBy {
                it.triggerAtMillis
            }

    val overdueCount =
        overdueLoanReminders.size

    val todayCount =
        activeReminders.count {
            isToday(it, todayStart)
        }

    val nextThreeDaysCount =
        activeReminders.count {
            it.triggerAtMillis >= todayStart &&
                it.triggerAtMillis < threeDaysEnd
        }

    val dueAmount =
        activeReminders
            .filter {
                it.triggerAtMillis >= todayStart &&
                    it.triggerAtMillis < threeDaysEnd
            }
            .sumOf {
                it.amount
            }

    val filtered =
        when (selectedFilter) {

            ReminderFilter.ALL ->
                reminders

            ReminderFilter.TODAY ->
                reminders.filter {
                    isToday(
                        it,
                        todayStart
                    ) &&
                        !it.isCompleted
                }

            ReminderFilter.NEXT_THREE_DAYS ->
                reminders.filter {
                    it.isActive &&
                        !it.isCompleted &&
                        it.triggerAtMillis >= todayStart &&
                        it.triggerAtMillis < threeDaysEnd
                }

            ReminderFilter.THIS_WEEK ->
                reminders.filter {
                    it.isActive &&
                        !it.isCompleted &&
                        it.triggerAtMillis >= todayStart &&
                        it.triggerAtMillis < weekEnd
                }

            ReminderFilter.OVERDUE ->
                overdueLoanReminders

            ReminderFilter.COMPLETED ->
                reminders.filter {
                    it.isCompleted
                }
        }
            .sortedWith(
                compareBy<Reminder> {
                    it.isCompleted
                }.thenBy {
                    it.triggerAtMillis
                }
            )

    val nextReminder =
        activeReminders
            .filter {
                !isOverdue(
                    it,
                    now
                )
            }
            .minByOrNull {
                it.triggerAtMillis
            }

    Scaffold(
        containerColor = MaterialTheme.colorScheme.background,

        topBar = {
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .background(MaterialTheme.colorScheme.background)
                    .padding(start = 16.dp, end = 12.dp, top = 12.dp, bottom = 8.dp),
                verticalAlignment = Alignment.CenterVertically
            ) {
                Column(modifier = Modifier.weight(1f)) {
                    Text(
                        text = "یادآوری‌ها",
                        style = MaterialTheme.typography.headlineSmall,
                        fontWeight = FontWeight.Bold,
                        color = MaterialTheme.colorScheme.onSurface
                    )
                    Spacer(Modifier.height(3.dp))
                    Text(
                        text = "مدیریت اقساط، پرداخت‌ها و رویدادهای مهم",
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                }
                IconButton(onClick = onBack) {
                    Icon(
                        imageVector = Icons.AutoMirrored.Filled.ArrowBack,
                        contentDescription = "بازگشت",
                        tint = MaterialTheme.colorScheme.onSurface
                    )
                }
            }
        },

        floatingActionButton = {
            AppFloatingActionButton(
                onClick = onAddReminder,
                shape = RoundedCornerShape(16.dp),
                containerColor = MaterialTheme.colorScheme.primary
            ) {
                Icon(
                    imageVector = Icons.Default.Add,
                    contentDescription = "یادآوری جدید"
                )
            }
        }

    ) { paddingValues ->

        LazyColumn(

            modifier =
                Modifier
                    .fillMaxSize()
                    .padding(
                        paddingValues
                    ),

            contentPadding =
                androidx.compose.foundation.layout.PaddingValues(
                    horizontal = 16.dp,
                    vertical = 16.dp
                ),

            verticalArrangement =
                Arrangement.spacedBy(
                    12.dp
                )
        ) {

            item {

                ReminderHeader(
                    todayCount = todayCount,
                    overdueCount = overdueCount,
                    nextThreeDaysCount =
                        nextThreeDaysCount,
                    dueAmount = dueAmount,
                    onSelectFilter = {
                        selectedFilter = it
                    }
                )
            }

            item {

                nextReminder?.let {

                    NextReminderCard(
                        reminder = it,
                        now = now
                    )
                }
            }

            item {

                Text(
                    text = "دسته‌بندی یادآوری‌ها",
                    style =
                        MaterialTheme.typography.titleMedium,
                    fontWeight =
                        FontWeight.Bold,
                    modifier =
                        Modifier.padding(
                            top = 4.dp,
                            bottom = 2.dp
                        )
                )
            }

            item {

                LazyFilterRow(
                    selectedFilter =
                        selectedFilter,
                    onSelected = {
                        selectedFilter = it
                    }
                )
            }

            if (filtered.isEmpty()) {

                item {

                    EmptyReminderCard(
                        filter =
                            selectedFilter,
                        onAddReminder =
                            onAddReminder
                    )
                }

            } else {

                items(
                    items = filtered,
                    key = {
                        it.id
                    }
                ) { reminder ->

                    ReminderItemCard(

                        reminder = reminder,

                        now = now,

                        onComplete = {

                            ReminderManager.setCompleted(
                                reminder.id,
                                !reminder.isCompleted
                            )

                            refreshKey++
                        },

                        onEdit = {
                            onEditReminder(
                                reminder
                            )
                        },

                        onDelete = {

                            ReminderManager.remove(
                                reminder.id
                            )

                            refreshKey++
                        }
                    )
                }
            }

            item {
                Spacer(
                    modifier =
                        Modifier.height(
                            80.dp
                        )
                )
            }
        }
    }
}

