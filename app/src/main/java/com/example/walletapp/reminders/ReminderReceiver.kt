package com.example.walletapp.reminders

import android.content.BroadcastReceiver
import android.content.Context
import android.content.Intent
import com.example.walletapp.data.LoanStore
import com.example.walletapp.data.ReminderStore
import com.example.walletapp.data.RepeatFrequency
import java.util.Calendar

class ReminderReceiver : BroadcastReceiver() {

    companion object {
        const val EXTRA_REMINDER_ID = "reminder_id"

        private const val STAGE_SEVEN_DAYS = 0
        private const val STAGE_THREE_DAYS = 1
        private const val STAGE_ONE_DAY = 2
        private const val STAGE_DUE_DATE = 3
        private const val STAGE_OVERDUE = 4

        private const val DAY_MILLIS = 24L * 60L * 60L * 1000L
    }

    override fun onReceive(
        context: Context,
        intent: Intent
    ) {
        val id = intent.getStringExtra(
            EXTRA_REMINDER_ID
        ) ?: return

        ReminderStore.attachContext(context)

        val reminder = ReminderStore.getById(id)
            ?: return

        if (!reminder.isActive || reminder.isCompleted) {
            return
        }

        /*
         * Auto-generated loan installment reminders have their own
         * lifecycle. They must not use the normal DAILY/WEEKLY/MONTHLY
         * repeat logic.
         */
        if (reminder.isAutoGenerated && reminder.sourceType == "LOAN_INSTALLMENT") {
            handleLoanInstallmentReminder(
                context = context,
                reminder = reminder
            )
            return
        }

        /*
         * Normal user-created reminders keep their original behaviour.
         */
        ReminderNotifier.notify(
            context,
            reminder
        )

        if (reminder.repeat == RepeatFrequency.ONCE) {
            ReminderStore.update(
                reminder.copy(
                    isActive = false
                )
            )
            return
        }

        val calendar = Calendar.getInstance().apply {
            timeInMillis = reminder.triggerAtMillis

            when (reminder.repeat) {
                RepeatFrequency.DAILY ->
                    add(Calendar.DAY_OF_MONTH, 1)

                RepeatFrequency.WEEKLY ->
                    add(Calendar.DAY_OF_MONTH, 7)

                RepeatFrequency.MONTHLY -> {
                    val originalDay =
                        get(Calendar.DAY_OF_MONTH)

                    add(Calendar.MONTH, 1)

                    val maxDay =
                        getActualMaximum(Calendar.DAY_OF_MONTH)

                    set(
                        Calendar.DAY_OF_MONTH,
                        minOf(originalDay, maxDay)
                    )
                }

                RepeatFrequency.ONCE -> Unit
            }
        }

        var nextMillis = calendar.timeInMillis

        if (nextMillis <= System.currentTimeMillis()) {
            nextMillis = System.currentTimeMillis() + 60_000L
        }

        val next = reminder.copy(
            triggerAtMillis = nextMillis
        )

        ReminderStore.update(next)

        ReminderScheduler.schedule(
            context,
            next
        )
    }

    private fun handleLoanInstallmentReminder(
        context: Context,
        reminder: com.example.walletapp.data.Reminder
    ) {
        val loanId = reminder.sourceId
        val installmentNumber = reminder.sourceInstallmentNumber
        val dueAtMillis = reminder.dueAtMillis

        if (
            loanId.isNullOrBlank() ||
            installmentNumber == null ||
            dueAtMillis == null
        ) {
            /*
             * An auto-generated installment reminder without its source
             * identity cannot be verified against the loan/payment state.
             * Deactivate it silently rather than risk a false notification.
             */
            ReminderStore.update(
                reminder.copy(
                    isActive = false,
                    isCompleted = true
                )
            )

            return
        }

        /*
         * Check the actual loan/payment state before showing anything.
         *
         * This prevents a stale alarm from notifying the user after
         * the installment has already been paid.
         */
        val loan = LoanStore.getById(loanId)

        if (loan == null) {
            ReminderStore.update(
                reminder.copy(
                    isActive = false
                )
            )
            return
        }

        val alreadyPaid = loan.payments.any {
            it.installmentNumber == installmentNumber
        }

        if (alreadyPaid) {
            ReminderStore.update(
                reminder.copy(
                    isActive = false,
                    isCompleted = true
                )
            )
            return
        }

        /*
         * If the loan reminder was disabled, do not continue scheduling it.
         */
        if (!loan.reminderEnabled) {
            ReminderStore.update(
                reminder.copy(
                    isActive = false
                )
            )
            return
        }

        val now = System.currentTimeMillis()

        /*
         * If the alarm fired late and we have already passed the due date,
         * immediately move to overdue mode instead of showing an outdated
         * "days remaining" notification.
         */
        if (now >= dueAtMillis && reminder.notificationStage < STAGE_OVERDUE) {
            val overdueReminder = reminder.copy(
                notificationStage = STAGE_OVERDUE,
                triggerAtMillis = now
            )

            ReminderStore.update(overdueReminder)

            ReminderNotifier.notify(
                context,
                overdueReminder
            )

            scheduleNextOverdueNotification(
                context,
                overdueReminder
            )

            return
        }

        /*
         * Normal scheduled notification.
         */
        ReminderNotifier.notify(
            context,
            reminder
        )

        when (reminder.notificationStage) {

            STAGE_SEVEN_DAYS -> {
                scheduleLoanStage(
                    context = context,
                    reminder = reminder,
                    nextStage = STAGE_THREE_DAYS,
                    targetMillis = dueAtMillis - (3L * DAY_MILLIS)
                )
            }

            STAGE_THREE_DAYS -> {
                scheduleLoanStage(
                    context = context,
                    reminder = reminder,
                    nextStage = STAGE_ONE_DAY,
                    targetMillis = dueAtMillis - DAY_MILLIS
                )
            }

            STAGE_ONE_DAY -> {
                scheduleLoanStage(
                    context = context,
                    reminder = reminder,
                    nextStage = STAGE_DUE_DATE,
                    targetMillis = dueAtMillis
                )
            }

            STAGE_DUE_DATE -> {
                val overdueStart =
                    maxOf(
                        dueAtMillis + 60_000L,
                        now + 60_000L
                    )

                scheduleLoanStage(
                    context = context,
                    reminder = reminder,
                    nextStage = STAGE_OVERDUE,
                    targetMillis = overdueStart
                )
            }

            STAGE_OVERDUE -> {
                scheduleNextOverdueNotification(
                    context,
                    reminder
                )
            }

            else -> {
                /*
                 * Unknown stage: safely restart from the next meaningful
                 * point rather than creating a broken alarm.
                 */
                val target =
                    if (dueAtMillis > now) {
                        dueAtMillis
                    } else {
                        now + 60_000L
                    }

                val safeStage =
                    if (dueAtMillis > now) {
                        STAGE_DUE_DATE
                    } else {
                        STAGE_OVERDUE
                    }

                scheduleLoanStage(
                    context = context,
                    reminder = reminder,
                    nextStage = safeStage,
                    targetMillis = target
                )
            }
        }
    }

    private fun scheduleLoanStage(
        context: Context,
        reminder: com.example.walletapp.data.Reminder,
        nextStage: Int,
        targetMillis: Long
    ) {
        val now = System.currentTimeMillis()

        val safeTarget =
            if (targetMillis > now) {
                targetMillis
            } else {
                now + 60_000L
            }

        val next = reminder.copy(
            notificationStage = nextStage,
            triggerAtMillis = safeTarget,
            isActive = true
        )

        ReminderStore.update(next)

        ReminderScheduler.schedule(
            context,
            next
        )
    }

    private fun scheduleNextOverdueNotification(
        context: Context,
        reminder: com.example.walletapp.data.Reminder
    ) {
        val nextMillis =
            System.currentTimeMillis() + DAY_MILLIS

        val next = reminder.copy(
            notificationStage = STAGE_OVERDUE,
            triggerAtMillis = nextMillis,
            isActive = true
        )

        ReminderStore.update(next)

        ReminderScheduler.schedule(
            context,
            next
        )
    }
}
