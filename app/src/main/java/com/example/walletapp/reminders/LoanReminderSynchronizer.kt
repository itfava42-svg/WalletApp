package com.example.walletapp.reminders

import android.content.Context
import com.example.walletapp.data.JalaliCalendar
import com.example.walletapp.data.LoanEntry
import com.example.walletapp.data.LoanStore
import com.example.walletapp.data.Reminder
import com.example.walletapp.data.ReminderCategory
import com.example.walletapp.data.ReminderKind
import com.example.walletapp.data.ReminderPriority
import com.example.walletapp.data.ReminderStore
import com.example.walletapp.data.RepeatFrequency
import java.util.Calendar

/**
 * Keeps automatic loan-installment reminders synchronized with loans.
 *
 * One Reminder is created for each unpaid installment.
 *
 * Stable identity:
 * loan id + installment number
 *
 * This prevents duplicate reminders when synchronization runs multiple
 * times or when the loan is edited.
 */
object LoanReminderSynchronizer {

    private const val SOURCE_TYPE =
        "LOAN_INSTALLMENT"

    fun syncAll(
        context: Context
    ) {

        ReminderStore.attachContext(context)
        LoanStore.attachContext(context)

        LoanStore.loans
            .forEach {
                syncLoan(
                    context,
                    it
                )
            }

        removeOrphans(context)
    }

    fun syncLoan(
        context: Context,
        loan: LoanEntry
    ) {

        ReminderStore.attachContext(context)

        val existing =
            ReminderStore.reminders
                .filter {
                    it.isAutoGenerated &&
                        it.sourceType == SOURCE_TYPE &&
                        it.sourceId == loan.id
                }

        // If automatic reminders are disabled for this loan,
        // cancel/remove all generated reminders belonging to it.
        if (!loan.reminderEnabled) {

            existing.forEach {
                ReminderScheduler.cancel(
                    context,
                    it
                )

                ReminderStore.remove(
                    it.id
                )
            }

            return
        }

        val paid =
            (1..loan.totalInstallments)
                .filter { loan.isInstallmentPaid(it) }
                .toSet()

        for (
            installmentNumber
            in 1..loan.totalInstallments
        ) {

            if (
                paid.contains(
                    installmentNumber
                )
            ) {

                removeInstallmentReminder(
                    context,
                    loan.id,
                    installmentNumber
                )

                continue
            }

            val dueDate =
                loan.installmentDueDateParts(
                    installmentNumber
                )

            if (dueDate == null) {
                // A reminder without a valid due date must not keep
                // an older alarm alive after the loan has been edited.
                removeInstallmentReminder(
                    context,
                    loan.id,
                    installmentNumber
                )
                continue
            }

            val dueAtMillis =
                JalaliCalendar.jalaliToEpochMillis(
                    dueDate.first,
                    dueDate.second,
                    dueDate.third
                )

            val reminderId =
                reminderId(
                    loan.id,
                    installmentNumber
                )

            val current =
                ReminderStore.getById(
                    reminderId
                )

            val nextTrigger =
                calculateNextTrigger(
                    dueAtMillis,
                    System.currentTimeMillis()
                )

            val reminder =
                Reminder(
                    id = reminderId,

                    title =
                        "قسط شماره $installmentNumber وام ${loan.title}",

                    amount =
                        loan.installmentAmount,

                    kind =
                        ReminderKind.PAY,

                    description =
                        "یادآوری خودکار قسط شماره $installmentNumber",

                    repeat =
                        RepeatFrequency.ONCE,

                    triggerAtMillis =
                        nextTrigger.first,

                    isActive =
                        true,

                    priority =
                        priorityFor(
                            nextTrigger.second
                        ),

                    category =
                        ReminderCategory.INSTALLMENT,

                    isCompleted =
                        false,

                    sourceType =
                        SOURCE_TYPE,

                    sourceId =
                        loan.id,

                    sourceInstallmentNumber =
                        installmentNumber,

                    dueAtMillis =
                        dueAtMillis,

                    notificationStage =
                        nextTrigger.second,

                    isAutoGenerated =
                        true
                )

            if (current == null) {

                ReminderStore.add(
                    reminder
                )

            } else {

                ReminderStore.update(
                    reminder
                )
            }

            ReminderScheduler.schedule(
                context,
                reminder
            )
        }

        // Remove generated reminders for installment numbers
        // that no longer exist after editing the loan.
        existing
            .filter {
                val number =
                    it.sourceInstallmentNumber

                number == null ||
                    number > loan.totalInstallments
            }
            .forEach {

                ReminderScheduler.cancel(
                    context,
                    it
                )

                ReminderStore.remove(
                    it.id
                )
            }
    }

    fun removeLoan(
        context: Context,
        loanId: String
    ) {

        ReminderStore.attachContext(
            context
        )

        ReminderStore.reminders
            .filter {
                it.isAutoGenerated &&
                    it.sourceType == SOURCE_TYPE &&
                    it.sourceId == loanId
            }
            .forEach {

                ReminderScheduler.cancel(
                    context,
                    it
                )

                ReminderStore.remove(
                    it.id
                )
            }
    }

    fun completeInstallment(
        context: Context,
        loanId: String,
        installmentNumber: Int
    ) {

        ReminderStore.attachContext(
            context
        )

        val reminderId =
            reminderId(
                loanId,
                installmentNumber
            )

        ReminderStore.getById(
            reminderId
        )?.let {

            ReminderScheduler.cancel(
                context,
                it
            )

            ReminderStore.setCompleted(
                reminderId,
                true
            )
        }
    }

    private fun removeInstallmentReminder(
        context: Context,
        loanId: String,
        installmentNumber: Int
    ) {

        val id =
            reminderId(
                loanId,
                installmentNumber
            )

        ReminderStore.getById(id)?.let {

            ReminderScheduler.cancel(
                context,
                it
            )

            ReminderStore.remove(id)
        }
    }

    private fun removeOrphans(
        context: Context
    ) {

        val loanIds =
            LoanStore.loans
                .map {
                    it.id
                }
                .toSet()

        ReminderStore.reminders
            .filter {
                it.isAutoGenerated &&
                    it.sourceType == SOURCE_TYPE &&
                    (
                        it.sourceId == null ||
                            !loanIds.contains(
                                it.sourceId
                            )
                    )
            }
            .forEach {

                ReminderScheduler.cancel(
                    context,
                    it
                )

                ReminderStore.remove(
                    it.id
                )
            }
    }

    private fun reminderId(
        loanId: String,
        installmentNumber: Int
    ): String =
        "loan_installment_${loanId}_$installmentNumber"

    /**
     * Returns:
     * Pair(triggerMillis, stage)
     *
     * Stage 0: 7 days before
     * Stage 1: 3 days before
     * Stage 2: 1 day before
     * Stage 3: due date
     * Stage 4: overdue
     */
    private fun calculateNextTrigger(
        dueAtMillis: Long,
        now: Long
    ): Pair<Long, Int> {

        val stages =
            listOf(
                7L to 0,
                3L to 1,
                1L to 2,
                0L to 3
            )

        for (
            (daysBefore, stage)
            in stages
        ) {

            val trigger =
                dueAtMillis -
                    daysBefore *
                    24L *
                    60L *
                    60L *
                    1000L

            if (trigger > now + 60_000L) {
                return trigger to stage
            }
        }

        // Already due or overdue.
        return (
            now + 60_000L
        ) to 4
    }

    private fun priorityFor(
        stage: Int
    ): ReminderPriority =
        when (stage) {
            0 -> ReminderPriority.MEDIUM
            1 -> ReminderPriority.HIGH
            2 -> ReminderPriority.HIGH
            3 -> ReminderPriority.URGENT
            else -> ReminderPriority.URGENT
        }
}
